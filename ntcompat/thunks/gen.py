"""Generate the ntcompat import-thunk tables from thunks.tsv.

    python3 ntcompat/thunks/gen.py                 write imp_x86.asm and thunk_table.h
    python3 ntcompat/thunks/gen.py --check         fail if they are out of date
    python3 ntcompat/thunks/gen.py --check-imports FILE...
                                                   fail if a PE file still imports a
                                                   thunked function from its DLL

imp_x86.asm (set "core") and imp_noyy_x86.asm (set "noyy", for builds
without YY-Thunks) define, for each function, the __imp_ pointer that callers of
a dllimport function read (for example __imp__GetFileSizeEx@8), pointing at
ntcompat's stub. Linked as an object, it is found before the system import
library, so the import never reaches the PE import table.

imp_lazy_x86.asm (set "lazy") needs no C code per function. Each pointer
starts at a generated binder: on the first call it looks the function up in
the listed DLLs, in order (for example ws2_32, then wsock32 on NT 3.51),
patches the pointer and jumps there; if no DLL has it, it points the import
at a generated stub that sets an error code and returns a failure value,
popping the stdcall arguments. lazy_table.h describes the rows for lazy.c.
"""

import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
TABLE = os.path.join(HERE, "thunks.tsv")
ASM = os.path.join(HERE, "imp_x86.asm")
ASM_NOYY = os.path.join(HERE, "imp_noyy_x86.asm")
ASM_LAZY = os.path.join(HERE, "imp_lazy_x86.asm")
LAZY_HEADER = os.path.join(HERE, "lazy_table.h")
SETS = ("core", "noyy", "lazy")
HEADER = os.path.join(HERE, "thunk_table.h")

LICENSE_ASM = """; This Source Code Form is subject to the terms of the Mozilla Public
; License, v. 2.0. If a copy of the MPL was not distributed with this
; file, You can obtain one at http://mozilla.org/MPL/2.0/.
"""
LICENSE_C = """/* This Source Code Form is subject to the terms of the Mozilla Public
 * License, v. 2.0. If a copy of the MPL was not distributed with this
 * file, You can obtain one at http://mozilla.org/MPL/2.0/. */
"""


def read_table(path=TABLE):
    rows = []
    with open(path) as f:
        for n, line in enumerate(f, 1):
            line = line.split("#", 1)[0].strip() if line.lstrip().startswith("#") else line.strip()
            if not line:
                continue
            parts = line.split(None, 5)
            if len(parts) < 5:
                raise SystemExit(f"{path}:{n}: expected dll, function, args, since, set")
            dll, func, args, since, which = parts[:5]
            if which not in SETS:
                raise SystemExit(f"{path}:{n}: set must be one of {SETS}")
            major, minor = (int(x) for x in since.split("."))
            if int(args) % 4:
                raise SystemExit(f"{path}:{n}: argument bytes must be a multiple of 4")
            note = parts[5] if len(parts) > 5 else ""
            row = {"dll": dll.lower(), "func": func, "args": int(args),
                   "since": (major, minor), "set": which, "note": note}
            if which == "lazy":
                # "ws2_32|wsock32": the first DLL from `since`, the others always.
                dlls = []
                for i, item in enumerate(dll.lower().split("|")):
                    name, _, ver = item.partition("@")
                    vmaj, vmin = ((int(x) for x in ver.split(".")) if ver
                                  else ((major, minor) if i == 0 else (3, 10)))
                    dlls.append((name if "." in name else name + ".dll", vmaj, vmin))
                row["dlls"] = dlls
                fields = dict(f.split("=", 1) for f in note.split()
                              if "=" in f and f.split("=", 1)[0] in ("fail", "err"))
                if "fail" not in fields or "err" not in fields:
                    raise SystemExit(f"{path}:{n}: lazy rows need fail=VALUE err=CODE in the note")
                row["fail"] = int(fields["fail"], 0) & 0xFFFFFFFF
                row["err"] = int(fields["err"], 0)
            else:
                if "|" in dll:
                    raise SystemExit(f"{path}:{n}: only lazy rows may list several DLLs")
                row["dlls"] = [(dll.lower() + ".dll", major, minor)]
            rows.append(row)
    names = [r["func"] for r in rows]
    dupes = sorted({x for x in names if names.count(x) > 1})
    if dupes:
        raise SystemExit(f"{path}: functions listed twice: {', '.join(dupes)}")
    return rows


def render_asm(rows, which):
    rows = [r for r in rows if r["set"] == which]
    out = [LICENSE_ASM,
           f"; Generated by ntcompat/thunks/gen.py from thunks.tsv (set \"{which}\"). Do not edit.\n",
           "        .386",
           "        .model flat",
           ""]
    for r in rows:
        name = f"{r['func']}@{r['args']}"
        out.append(f"        EXTERN _ntcompat_{name}:PROC")
        out.append(f"        PUBLIC __imp__{name}, _{name}")
    out += ["",
            "; The pointers that dllimport callers read.",
            "        .data"]
    for r in rows:
        name = f"{r['func']}@{r['args']}"
        out.append(f"__imp__{name} DD _ntcompat_{name}")
    out += ["",
            "; Direct-call entry points, as an import library would provide. Without",
            "; them a direct call pulls in the import library's member, which",
            "; defines __imp_ a second time.",
            "        .code"]
    for r in rows:
        name = f"{r['func']}@{r['args']}"
        out += [f"_{name} PROC",
                f"        jmp DWORD PTR [__imp__{name}]",
                f"_{name} ENDP"]
    out += ["", "        END", ""]
    return "\n".join(out)


def render_lazy_asm(rows):
    rows = [r for r in rows if r["set"] == "lazy"]
    out = [LICENSE_ASM,
           "; Generated by ntcompat/thunks/gen.py from thunks.tsv (set \"lazy\"). Do not edit.",
           "; See gen.py for how the binders and failure stubs work.\n",
           "        .386",
           "        .model flat",
           "",
           "        EXTERN _ntcompat_lazy_resolve@4:PROC",
           "        EXTERN _ntcompat_lazy_failed@4:PROC",
           "        PUBLIC _ntcompat_lazy_slots, _ntcompat_lazy_fail_stubs, _ntcompat_lazy_binders"]
    for r in rows:
        name = f"{r['func']}@{r['args']}"
        out.append(f"        PUBLIC __imp__{name}, _{name}")
    out += ["",
            "; The pointers dllimport callers read, in table order. Each starts at its",
            "; binder and is replaced by the resolved function (or its failure stub).",
            "        .data"]
    for i, r in enumerate(rows):
        name = f"{r['func']}@{r['args']}"
        label = "_ntcompat_lazy_slots " if i == 0 else ""
        out.append(f"{label}__imp__{name} DD ntc_bind_{i}")
    if not rows:
        out.append("_ntcompat_lazy_slots DD 0")
    out += ["", "; Where each binder and failure stub is, for lazy.c."]
    out.append("_ntcompat_lazy_binders " + ("DD " + ", ".join(f"ntc_bind_{i}" for i in range(len(rows)))
                                            if rows else "DD 0"))
    out.append("_ntcompat_lazy_fail_stubs " + ("DD " + ", ".join(f"ntc_fail_{i}" for i in range(len(rows)))
                                               if rows else "DD 0"))
    out += ["", "        .code"]
    for i, r in enumerate(rows):
        name = f"{r['func']}@{r['args']}"
        out += [f"; {r['func']}: {' | '.join(d[0] for d in r['dlls'])}",
                f"ntc_bind_{i} PROC",
                f"        push {i}",
                "        call _ntcompat_lazy_resolve@4   ; returns the target, patches the slot",
                "        jmp eax                          ; arguments and return address untouched",
                f"ntc_bind_{i} ENDP",
                f"ntc_fail_{i} PROC",
                f"        push {i}",
                "        call _ntcompat_lazy_failed@4    ; sets the error, returns the value",
                f"        ret {r['args']}" if r["args"] else "        ret",
                f"ntc_fail_{i} ENDP",
                f"_{name} PROC",
                f"        jmp DWORD PTR [__imp__{name}]",
                f"_{name} ENDP"]
    out += ["", "        END", ""]
    return "\n".join(out)


def render_lazy_header(rows):
    rows = [r for r in rows if r["set"] == "lazy"]
    out = [LICENSE_C,
           "/* Generated by ntcompat/thunks/gen.py from thunks.tsv (set \"lazy\"). Do not edit.",
           " * NTCOMPAT_LAZY(function, \"dll@maj.min|...\", fail value, error code) */", ""]
    for r in rows:
        dlls = "|".join(f"{d}@{a}.{b}" for d, a, b in r["dlls"])
        out.append(f"NTCOMPAT_LAZY({r['func']}, \"{dlls}\", 0x{r['fail']:08X}u, {r['err']}u)")
    out.append("")
    return "\n".join(out)


def render_header(rows):
    rows = [r for r in rows if r["set"] != "lazy"]
    out = [LICENSE_C,
           "/* Generated by ntcompat/thunks/gen.py from thunks.tsv. Do not edit.",
           " * NTCOMPAT_THUNK(dll, function, since_major, since_minor) */", ""]
    for r in rows:
        out.append(f"NTCOMPAT_THUNK(\"{r['dll']}.dll\", {r['func']}, {r['since'][0]}, {r['since'][1]})")
    out.append("")
    return "\n".join(out)


def outputs(rows):
    return {ASM: render_asm(rows, "core"), ASM_NOYY: render_asm(rows, "noyy"),
            HEADER: render_header(rows), ASM_LAZY: render_lazy_asm(rows),
            LAZY_HEADER: render_lazy_header(rows)}


def check_imports(paths, rows):
    sys.path.insert(0, os.path.join(HERE, "..", "..", "tuatara", "tools"))
    from apiaudit import pe  # noqa: E402

    wanted = {(d[0], r["func"]) for r in rows for d in r["dlls"]}
    bad = []
    for path in paths:
        img = pe.parse(path)
        for imp in img.imports:
            for sym in imp.symbols:
                if (imp.dll.lower(), sym.name) in wanted:
                    bad.append(f"{path}: still imports {imp.dll}!{sym.name}")
    for line in bad:
        print(line)
    if not bad:
        print(f"ok: none of {len(rows)} thunked functions imported by {len(paths)} files")
    return 1 if bad else 0


def main(argv):
    rows = read_table()
    if argv and argv[0] == "--check-imports":
        return check_imports(argv[1:], rows)
    stale = []
    for path, text in outputs(rows).items():
        try:
            with open(path, newline="") as f:
                current = f.read()
        except FileNotFoundError:
            current = None
        if current != text:
            if argv and argv[0] == "--check":
                stale.append(os.path.basename(path))
            else:
                with open(path, "w", newline="\n") as f:
                    f.write(text)
                print(f"wrote {os.path.relpath(path)}")
    if stale:
        print("out of date (run python3 ntcompat/thunks/gen.py): " + ", ".join(stale))
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
